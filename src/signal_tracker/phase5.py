"""Command line entry points for the static site and scheduled runner."""

import argparse
import logging
import os
import sqlite3
import time
from pathlib import Path
from threading import Event, Thread

from .automation import tick
from .biquote import SOURCE as BIQUOTE_SOURCE
from .phase2 import DEFAULT_DB
from .public_snapshot import GOLD_AUDIT, atomic_json, make_snapshot
from .signal import now_utc
from .sources import OANDA_SOURCE
from .telegram import flush_alerts, verify_public_channel
from .telegram_subscriptions import run_subscription_worker

PUBLIC_SNAPSHOT = Path("artifacts/signal-tracker/public/data/snapshot.json")
PREVIEW_STATE = Path("generated-artifacts/biquote-preview")
LOG = logging.getLogger(__name__)


def add_phase5(commands: argparse._SubParsersAction) -> None:
    site = commands.add_parser("export-site", help="Export the website's public JSON snapshot from real records")
    site.add_argument("--output", type=Path, default=PUBLIC_SNAPSHOT)
    site.add_argument("--backtest-report", type=Path, action="append",
                      help="Additional comparable BACKTEST report, repeatable")
    site.add_argument("--runner-status", type=Path, help="Status generated by the scheduled runner")
    runner = commands.add_parser("scheduled-tick", help="Check existing LIVE records and scan one prospective setup")
    runner.add_argument("--calendar", type=Path, help="Reviewed calendar with reported verification time and coverage")
    runner.add_argument("--runner-status", type=Path, required=True)
    runner.add_argument("--strategy", action="append", help="Scan only these frozen rule versions, repeatable")
    runner.add_argument("--feed", choices=("oanda", "biquote"), default="oanda")
    runner.add_argument("--private-h1-cache", type=Path, help="Optional private Biquote H1 warm-up file; never publish it")
    alerts = commands.add_parser("send-alerts", help="Deliver pending LIVE Telegram alerts to the configured chat")
    commands.add_parser("check-telegram-channel", help="Verify the public channel and bot permissions without posting")
    loop = commands.add_parser("preview-scanner", help="Run the free Biquote test scanner while the workspace is awake")
    loop.add_argument("--once", action="store_true", help="Scan and export one update, then exit")
    loop.add_argument("--strategy", action="append", help="Run only these Biquote versions, repeatable")
    for command in (site, runner, alerts):
        command.add_argument("--db", type=Path, default=DEFAULT_DB)


def run_phase5(args: argparse.Namespace) -> None:
    if args.command == "export-site":
        bundled = sorted(GOLD_AUDIT.parent.glob("xauusd-cld-*-2023-2024.json"))
        reports = list(dict.fromkeys(path.resolve() for path in [*bundled, *(args.backtest_report or [])]))
        snapshot = make_snapshot(args.config_dir, args.db, reports, args.runner_status)
        atomic_json(args.output, snapshot, public=True)
        print(f"Exported {len(snapshot['cohorts'])} separate scopes to {args.output}")
    elif args.command == "scheduled-tick":
        if args.feed == "biquote":
            status = tick(args.config_dir, args.db, None, args.strategy, feed=BIQUOTE_SOURCE, cache=args.private_h1_cache)
        else:
            status = tick(args.config_dir, args.db, args.calendar, args.strategy, feed=OANDA_SOURCE)
        atomic_json(args.runner_status, status)
        print(status["message"])
        if status["state"] == "error":
            raise ValueError("Market update incomplete; see runner status. Existing records remain intact.")
    elif args.command == "check-telegram-channel":
        verify_public_channel()
        LOG.info("Telegram public channel verified; no message was posted")
    elif args.command == "preview-scanner":
        db, status_path = PREVIEW_STATE / "signals.db", PREVIEW_STATE / "runner-status.json"
        reports = sorted(GOLD_AUDIT.parent.glob("xauusd-cld-*-2023-2024.json"))
        telegram_started = now_utc() if os.environ.get("TRACKER_PREVIEW_TELEGRAM") == "true" else None
        telegram_channel_id = None
        # The opt-in bot reads Telegram commands independently of market scans.
        if telegram_started is not None and not args.once and os.environ.get("TRACKER_TELEGRAM_SELF_SERVICE") == "true":
            stop = Event()
            Thread(target=run_subscription_worker, args=(db, args.config_dir, stop),
                   name="telegram-subscriptions", daemon=True).start()
        while True:
            try:
                status = tick(args.config_dir, db, None, args.strategy, feed=BIQUOTE_SOURCE,
                              cache=PREVIEW_STATE / "private-h1.json")
                atomic_json(status_path, status)
                snapshot = make_snapshot(args.config_dir, db, reports, status_path)
                atomic_json(PREVIEW_STATE / "snapshot.json", snapshot, public=True)
                LOG.info("%s", status["message"])
                if telegram_started is not None:
                    try:
                        if telegram_channel_id is None:
                            telegram_channel_id = verify_public_channel()
                            LOG.info("Telegram public channel verified; configured alerts enabled")
                        flush_alerts(db, args.config_dir, preview_started=telegram_started,
                                     preview_channel_id=telegram_channel_id)
                    except (OSError, ValueError, sqlite3.Error) as error:
                        telegram_channel_id = None
                        detail = str(error) if isinstance(error, ValueError) else type(error).__name__
                        LOG.warning("Telegram delivery skipped: %s", detail)
            except (KeyError, OSError, ValueError) as error:
                if args.once:
                    raise
                LOG.error("Could not refresh the Biquote preview: %s", error)
            if args.once:
                break
            # Wake just after the next closed five-minute candle.
            time.sleep(max(1.0, 300.0 - time.time() % 300.0 + 2.0))
    else:
        flush_alerts(args.db, args.config_dir)
